import { HttpStatus, Inject, Injectable } from "@nestjs/common";
import { createWriteStream } from "node:fs";
import { access, copyFile, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";
import { Transform, type Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { AppError } from "../../common/errors/app-error";
import { ENV } from "../../config/config.module";
import type { Env } from "../../config/env";
import { StorageDriver, type UploadTarget } from "./storage.driver";

/** Files on disk under STORAGE_LOCAL_DIR; served publicly at /media-files */
@Injectable()
export class LocalStorageDriver extends StorageDriver {
  readonly root: string;

  constructor(@Inject(ENV) private readonly env: Env) {
    super();
    this.root = resolve(env.STORAGE_LOCAL_DIR);
  }

  /** Keys are generated by the API, but never trust a path to stay inside the root */
  pathOf(key: string): string {
    const path = resolve(join(this.root, key));
    if (!path.startsWith(this.root + sep)) throw new Error(`Storage key escapes root: ${key}`);
    return path;
  }

  createUploadTarget(mediaId: string, _key: string, mime: string): UploadTarget {
    return {
      url: `${this.env.API_PUBLIC_URL.replace(/\/$/, "")}/api/v1/media/${mediaId}/upload`,
      method: "PUT",
      headers: { "Content-Type": mime },
    };
  }

  async writeStream(key: string, body: Readable, maxBytes: number): Promise<number> {
    const path = this.pathOf(key);
    await mkdir(dirname(path), { recursive: true });

    let written = 0;
    const limit = new Transform({
      transform(chunk: Buffer, _encoding, callback) {
        written += chunk.length;
        if (written > maxBytes) {
          callback(new AppError("FILE_TOO_LARGE", "File is larger than declared", HttpStatus.PAYLOAD_TOO_LARGE));
          return;
        }
        callback(null, chunk);
      },
    });

    try {
      await pipeline(body, limit, createWriteStream(path));
    } catch (error) {
      await rm(path, { force: true });
      throw error;
    }
    return written;
  }

  async putObject(key: string, body: Buffer): Promise<void> {
    const path = this.pathOf(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
  }

  async downloadToFile(key: string, path: string): Promise<void> {
    await copyFile(this.pathOf(key), path);
  }

  async exists(key: string): Promise<boolean> {
    try {
      await access(this.pathOf(key));
      return true;
    } catch {
      return false;
    }
  }

  async deleteObjects(keys: string[]): Promise<void> {
    await Promise.all(keys.map((key) => rm(this.pathOf(key), { force: true })));
  }
}
